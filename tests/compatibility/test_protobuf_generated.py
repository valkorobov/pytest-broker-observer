"""Exercise real protoc output across the selected runtime generations.

The newer fixture has an explicit version-rejection outcome on the minimum
runtime. It is never skipped or rewritten to bypass Protobuf's version guard.
"""

import asyncio
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

from google.protobuf import __version__ as protobuf_version
from google.protobuf.runtime_version import VersionError
import pytest

from event_observer import EventObserver, RawEvent, SyncEventObserver
from event_observer.decoders import HeaderTypeResolver, ProtobufDecoder, ResolvingProtobufDecoder
from event_observer.errors import InvalidPayloadError, NullPayloadError
from event_observer.matchers import field_equals
from event_observer.testing import FakeTransport


FIXTURES = Path(__file__).with_name("protobuf")
GENERATIONS = {"v526": ("1.64.1", "5.26.1"), "v528": ("1.68.1", "5.28.1"), "current": ("1.85.1", "7.35.1")}


def generated(generation):
    """Load untouched generated bytes from their distinct descriptor namespaces."""
    name = f"observer_{generation}_pb2"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, FIXTURES / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    try:
        spec.loader.exec_module(module)
    except Exception:
        sys.modules.pop(name, None)
        raise
    return module


def observe_copies(message_type, sync):
    """Verify optional/repeated/map/oneof fields survive decoding and result copies."""
    transport = FakeTransport()
    original = message_type(
        operation_id="operation-42", status="completed", labels=["received"], counts={"ready": 1}, amount=42
    )
    wire = original.SerializeToString()

    def verify_result(event):
        assert event.raw.payload == wire
        assert event.payload.HasField("status")
        assert event.payload.WhichOneof("change") == "amount"
        assert event.payload.amount == 42
        event.payload.labels.append("mutated")
        event.payload.counts["ready"] = 999

    def verify_canonical(message):
        assert list(message.labels) == ["received"]
        assert dict(message.counts) == {"ready": 1}

    if sync:
        with SyncEventObserver(transport=transport).watch(
            source="generated.events", message_type=message_type
        ) as watcher:
            mark = watcher.mark()
            transport.publish(wire, source="generated.events")
            verify_result(watcher.wait_for_event(field_equals("status", "completed"), since=mark, timeout=1))
            verify_canonical(watcher.wait_for(field_equals("operation_id", "operation-42"), timeout=1))
    else:

        async def scenario():
            async with EventObserver(transport=transport).watch(
                source="generated.events", message_type=message_type
            ) as watcher:
                mark = watcher.mark()
                transport.publish(wire, source="generated.events")
                verify_result(
                    await watcher.wait_for_event(field_equals("status", "completed"), since=mark, timeout=1)
                )
                verify_canonical(
                    await watcher.wait_for(field_equals("operation_id", "operation-42"), timeout=1)
                )

        asyncio.run(scenario())


@pytest.mark.parametrize("generation", GENERATIONS)
def test_generated_fixture_has_exact_toolchain_and_content_provenance(generation):
    report = json.loads((FIXTURES / f"{generation}.json").read_text(encoding="utf-8"))
    generator, gencode = GENERATIONS[generation]
    assert report["generation"] == generation
    assert report["generator"]["version"] == generator
    assert report["gencode_version"] == gencode
    assert report["command"] == [
        "python",
        "-m",
        "grpc_tools.protoc",
        "--proto_path=.",
        "--python_out=.",
        f"observer_{generation}.proto",
    ]
    for key in ("source", "generated"):
        assert (
            hashlib.sha256((FIXTURES / report[key]["file"]).read_bytes()).hexdigest() == report[key]["sha256"]
        )


@pytest.mark.parametrize("generation", ["v526", "v528"])
@pytest.mark.parametrize("sync", [False, True], ids=["async", "sync"])
def test_older_generated_messages_work_through_both_facades(generation, sync):
    observe_copies(generated(generation).Observation, sync)


@pytest.mark.parametrize("generation", ["v526", "v528"])
def test_real_generated_decoders_preserve_presence_and_distinguish_invalid_payloads(generation):
    message_type = generated(generation).Observation
    decoder = ProtobufDecoder(message_type)
    assert not decoder.decode(RawEvent(payload=b"", source="events")).HasField("status")
    value = message_type(status="")
    decoded = decoder.decode(RawEvent(payload=value.SerializeToString(), source="events"))
    assert decoded.HasField("status") and decoded.status == ""
    with pytest.raises(NullPayloadError):
        decoder.decode(RawEvent(payload=None, source="events"))
    with pytest.raises(InvalidPayloadError) as caught:
        decoder.decode(RawEvent(payload=b"\xff", source="events"))
    assert caught.value.__cause__ is not None


def test_explicit_resolver_distinguishes_real_generated_message_classes():
    first, second = (generated(generation).Observation for generation in ("v526", "v528"))
    decoder = ResolvingProtobufDecoder(
        resolver=HeaderTypeResolver(header="type", types={b"older": first, b"newer": second})
    )
    for discriminator, message_type in ((b"older", first), (b"newer", second)):
        value = decoder.decode(
            RawEvent(
                payload=message_type(operation_id="operation-42").SerializeToString(),
                source="events",
                headers=(("type", discriminator),),
            )
        )
        assert type(value) is message_type
        assert value.operation_id == "operation-42"


def test_newer_generated_code_has_explicit_runtime_acceptance_or_rejection():
    runtime = tuple(int(part) for part in protobuf_version.split(".")[:3])
    required = tuple(int(part) for part in GENERATIONS["current"][1].split("."))
    if runtime < required:
        with pytest.raises(VersionError, match="runtime"):
            generated("current")
    else:
        message_type = generated("current").Observation
        observe_copies(message_type, False)
        observe_copies(message_type, True)
